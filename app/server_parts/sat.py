def sat_analysis_prompt(question: dict) -> str:
    """Build the solve-and-analyze prompt for one SAT question."""
    parts = [
        SAT_ANALYSIS_PROMPT,
        "",
        f"Question ID: {question.get('stable_id') or '(unknown)'}",
        f"Domain: {question.get('domain') or '(unknown)'}",
        f"Difficulty: {question.get('difficulty') or '(unknown)'}",
        "",
        "Question:",
        str(question.get("prompt") or ""),
        "",
    ]
    choices = question.get("choices") or []
    if choices:
        parts.append("Choices:")
        for choice in choices:
            parts.append(
                f"{choice.get('id') or '?'}) {choice.get('text') or ''}"
            )
        parts.append("")
    parts.append(
        "Write the deep Analysis first, then give the highlighted correct "
        "answer only at the very end."
    )
    return "\n".join(parts)


